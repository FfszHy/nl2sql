import argparse
import random
from datetime import date, datetime, timedelta
from typing import Dict, List, Sequence, Tuple

import psycopg


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a PostgreSQL (Supabase compatible) benchmark schema with related tables and seed data."
    )
    parser.add_argument("--host", required=True, help="Supabase pooler host, e.g. aws-0-xxx.pooler.supabase.com")
    parser.add_argument("--port", type=int, default=5432)
    parser.add_argument("--user", required=True, help="e.g. postgres.<project_ref>")
    parser.add_argument("--password", required=True)
    parser.add_argument("--database", default="postgres")
    parser.add_argument("--sslmode", default="require")
    parser.add_argument("--seed", type=int, default=20260424)
    parser.add_argument("--city-count", type=int, default=30)
    parser.add_argument("--cinema-count", type=int, default=120)
    parser.add_argument("--movie-count", type=int, default=240)
    parser.add_argument("--screening-count", type=int, default=12000)
    parser.add_argument("--customer-count", type=int, default=9000)
    parser.add_argument("--order-count", type=int, default=45000)
    parser.add_argument("--review-count", type=int, default=18000)
    parser.add_argument("--batch-size", type=int, default=1000)
    parser.add_argument(
        "--recreate",
        action="store_true",
        help="Drop existing tables (cascade) before creating them again.",
    )
    return parser.parse_args()


def connect_database(args: argparse.Namespace) -> psycopg.Connection:
    return psycopg.connect(
        host=args.host,
        port=args.port,
        user=args.user,
        password=args.password,
        dbname=args.database,
        sslmode=args.sslmode,
        autocommit=False,
    )


